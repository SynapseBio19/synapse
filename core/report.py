"""Reproducible analysis report from the results stored in a pipeline.

The report records, for every stored analysis, the input sequence hash, the
parameters, warnings, limitations, timestamps and software versions, so that
the analysis can be re-run and compared. It describes computational results
only; it is not evidence of experimental validation.

Two formats:
* JSON - complete, including each analysis' data payload.
* Markdown - human-readable summary; payloads are referenced by SHA-256 of
  their canonical JSON form so the two files can be matched.
"""

from __future__ import annotations

import dataclasses
import datetime as _dt
import enum
import hashlib
import json
import math
import platform
from pathlib import Path
from typing import Any, Dict, List, Optional

from core.models import SYNAPSE_VERSION, AnalysisResult, sha256_text

REPORT_FORMAT_VERSION = 1

DISCLAIMER = (
    "Computational analysis generated by Synapse. Results depend on the stated "
    "parameters and models and have not been experimentally validated."
)


def to_jsonable(value: Any, _depth: int = 0) -> Any:
    """Convert analysis payloads (dataclasses, sets, tuples, NaN, ...) to JSON-safe data."""
    if _depth > 50:
        return repr(value)
    if value is None or isinstance(value, (bool, int, str)):
        return value
    if isinstance(value, float):
        if math.isnan(value):
            return "NaN"
        if math.isinf(value):
            return "Infinity" if value > 0 else "-Infinity"
        return value
    if isinstance(value, enum.Enum):
        return to_jsonable(value.value, _depth + 1)
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {
            f.name: to_jsonable(getattr(value, f.name), _depth + 1)
            for f in dataclasses.fields(value)
        }
    if isinstance(value, dict):
        return {str(k): to_jsonable(v, _depth + 1) for k, v in value.items()}
    if isinstance(value, (set, frozenset)):
        items = [to_jsonable(v, _depth + 1) for v in value]
        try:
            return sorted(items)
        except TypeError:
            return sorted(items, key=repr)
    if isinstance(value, (list, tuple)):
        return [to_jsonable(v, _depth + 1) for v in value]
    if isinstance(value, (_dt.date, _dt.datetime)):
        return value.isoformat()
    if isinstance(value, Path):
        return str(value)
    if hasattr(value, "to_dict") and callable(value.to_dict):
        try:
            return to_jsonable(value.to_dict(), _depth + 1)
        except Exception:  # noqa: BLE001 - fall back to repr below
            pass
    return repr(value)


def canonical_json(value: Any) -> str:
    return json.dumps(to_jsonable(value), sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def _context_of(pipeline_or_context: Any) -> Any:
    return getattr(pipeline_or_context, "context", pipeline_or_context)


def _input_section(context: Any) -> Dict[str, Any]:
    sequence = getattr(context, "sequence", "") or ""
    section: Dict[str, Any] = {
        "header": getattr(context, "header", ""),
        "length": len(sequence),
        "topology": getattr(context, "topology", "linear"),
        "sequence_sha256": sha256_text(sequence) if sequence else None,
    }
    record = getattr(context, "record", None)
    if record is not None and hasattr(record, "provenance"):
        section["record"] = record.provenance()
    return section


def build_analysis_report(pipeline_or_context: Any, *, generated_at: Optional[str] = None) -> Dict[str, Any]:
    """Collect all stored ``AnalysisResult`` objects into one report dict."""
    context = _context_of(pipeline_or_context)
    stored: Dict[str, List[AnalysisResult]] = getattr(context, "results", {}) or {}
    analyses: List[Dict[str, Any]] = []
    for module in sorted(stored):
        for index, result in enumerate(stored[module], start=1):
            data = to_jsonable(result.data)
            entry = to_jsonable(result.summary())
            entry["result_index"] = index
            entry["data_sha256"] = hashlib.sha256(
                canonical_json(data).encode("utf-8")
            ).hexdigest()
            entry["data"] = data
            analyses.append(entry)
    return {
        "report_format_version": REPORT_FORMAT_VERSION,
        "generated_at": generated_at or _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        "software": {
            "synapse_version": SYNAPSE_VERSION,
            "python_version": platform.python_version(),
            "platform": platform.platform(terse=True),
        },
        "input": _input_section(context),
        "analysis_count": len(analyses),
        "analyses": analyses,
        "disclaimer": DISCLAIMER,
    }


def _md_value(value: Any) -> str:
    text = json.dumps(value, ensure_ascii=False, sort_keys=True) if not isinstance(value, str) else value
    return text if len(text) <= 200 else text[:197] + "..."


def report_to_markdown(report: Dict[str, Any]) -> str:
    lines = ["# Synapse analysis report", ""]
    lines.append(f"Generated: {report['generated_at']}  ")
    software = report["software"]
    lines.append(
        f"Synapse {software['synapse_version']}, Python {software['python_version']}, {software['platform']}"
    )
    lines += ["", "## Input", ""]
    for key, value in report["input"].items():
        if key == "record":
            for rkey, rvalue in value.items():
                if rvalue not in (None, ""):
                    lines.append(f"- record.{rkey}: `{_md_value(rvalue)}`")
        else:
            lines.append(f"- {key}: `{_md_value(value)}`")
    lines += ["", f"## Analyses ({report['analysis_count']})", ""]
    if not report["analyses"]:
        lines.append("No analysis results are stored in this session.")
    for entry in report["analyses"]:
        lines.append(f"### {entry['module']} #{entry['result_index']}")
        lines.append("")
        lines.append(f"- created: {entry.get('created_at')}")
        if entry.get("input_description"):
            lines.append(f"- input: {entry['input_description']}")
        lines.append(f"- input sequence SHA-256: `{entry.get('input_sequence_sha256')}`")
        lines.append(f"- data SHA-256 (canonical JSON): `{entry['data_sha256']}`")
        parameters = entry.get("parameters") or {}
        if parameters:
            lines.append("- parameters:")
            for key in sorted(parameters):
                lines.append(f"  - {key}: `{_md_value(parameters[key])}`")
        else:
            lines.append("- parameters: none recorded")
        for title in ("warnings", "limitations"):
            items = entry.get(title) or []
            if items:
                lines.append(f"- {title}:")
                lines.extend(f"  - {item}" for item in items)
        lines.append("")
    lines += ["---", "", report["disclaimer"], ""]
    return "\n".join(lines)


def export_analysis_report(pipeline_or_context: Any, path: str) -> Path:
    """Write the report as .json (complete) or .md (summary)."""
    target = Path(path).expanduser()
    suffix = target.suffix.lower()
    if suffix not in {".json", ".md"}:
        raise ValueError("Report path must end with .json or .md")
    report = build_analysis_report(pipeline_or_context)
    target.parent.mkdir(parents=True, exist_ok=True)
    if suffix == ".json":
        text = json.dumps(report, indent=2, ensure_ascii=False, sort_keys=False) + "\n"
    else:
        text = report_to_markdown(report)
    target.write_text(text, encoding="utf-8")
    return target
